/// 后端 API 配置。
class ApiConfig {
  /// Flutter Web 跑在浏览器里，`localhost` 就是宿主机本身，直接写即可。
  ///
  /// ⚠️ 以后做 Android 端时要改这里 —— 模拟器里的 `localhost` 指模拟器自己，
  /// 必须用 `10.0.2.2`（Android 模拟器访问宿主机的专用地址）；
  /// 真机则要填 Mac 的局域网 IP。所以这个值要按平台判断，不能写死。
  static const String baseUrl = 'http://localhost:8080';

  /// 请求超时。
  ///
  /// ⚠️ 这个值必须【大于】最慢那个接口的耗时，否则会在服务端留下"孤儿查询"。
  ///
  /// 踩过的坑：原来写 5 秒，理由是"数据量不大"—— 这个判断是错的。
  /// `/api/product-ranking` 要全表聚合 1.96 亿行，正常 12 秒、受压时 25 秒以上。
  /// 客户端 5 秒就断开，而 ClickHouse 那边的查询不会跟着停，会一直跑完 ——
  /// 于是每次轮询都留下一个没人要的查询。前端每 10 秒轮询一次，
  /// 实测叠到 5 个并发、吃掉 2.9 GiB，撞穿 ClickHouse 的内存上限（4.66 GiB）
  /// 后连接被重置，Flink 的 sink 收到 Connection reset 抛异常，
  /// 结果【整条实时流作业挂掉】。
  ///
  /// 30 秒 > 最慢接口的 25 秒，客户端会等到结果，不再产生孤儿。
  /// 顺带一个好处：单次请求（最长 30 秒）现在长于排行页 10 秒的轮询间隔，
  /// 页面里的在途保护这才真正生效，服务端查询不会互相重叠。
  ///
  /// 更彻底的做法是按端点区分超时（实时总览短、商品排行长）。等排行榜改走
  /// 预聚合表之后就不需要了 —— 那时它也是毫秒级，这个值可以再调回来。
  static const Duration timeout = Duration(seconds: 30);
}
